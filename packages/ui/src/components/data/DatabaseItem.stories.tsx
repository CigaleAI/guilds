import type { Meta, StoryObj } from "@storybook/react-vite";
import { useState } from "react";
import { DatabaseItem } from "./DatabaseItem";
import { ListGroupLabel } from "./ListGroupLabel";

const meta: Meta<typeof DatabaseItem> = {
  title: "Components/Data/DatabaseItem",
  component: DatabaseItem,
};
export default meta;

type Story = StoryObj<typeof DatabaseItem>;

const groups = [
  {
    guild: "cigale-replies-auto",
    items: [{ id: "follow_replies", purpose: "Track the replies generated by agents", count: 85, age: "3d" }],
  },
  {
    guild: "degen-capital",
    items: [
      { id: "degen-meta", purpose: "Tracking web3 & crypto meta from the trenches", count: 9, age: "3d" },
      { id: "degen-orders", purpose: "Transaction orders to be executed", count: 2, age: "1d" },
      { id: "degen-project-monitoring", purpose: "Track changes in monitored projects", count: 93, age: "2d" },
      { id: "degen-projects", purpose: "Archive and catalog degen crypto projects", count: 90, age: "2d" },
    ],
  },
  {
    guild: "link-prospection",
    items: [{ id: "prospect-data-user", purpose: "A LinkedIn prospect database", count: 69, age: "22h" }],
  },
];

function GroupedDatabases() {
  const [selected, setSelected] = useState("degen-meta");
  return (
    <div className="flex max-w-xs flex-col gap-1 rounded-xl bg-surface p-3">
      {groups.map((group) => (
        <section key={group.guild} aria-label={group.guild} className="flex flex-col gap-1">
          <ListGroupLabel>{group.guild}</ListGroupLabel>
          {group.items.map((item) => (
            <DatabaseItem
              key={item.id}
              name={item.id}
              purpose={item.purpose}
              count={item.count}
              age={item.age}
              selected={selected === item.id}
              onClick={() => setSelected(item.id)}
            />
          ))}
        </section>
      ))}
    </div>
  );
}

export const GroupedList: Story = {
  render: () => <GroupedDatabases />,
};

export const PaperTone: Story = {
  render: () => (
    <div className="flex max-w-xs flex-col gap-1 rounded-xl bg-surface p-6">
      <DatabaseItem tone="paper" selected name="degen-meta" purpose="Tracking web3 & crypto meta" count={9} age="3d" />
      <DatabaseItem tone="paper" name="degen-orders" purpose="Transaction orders to be executed" count={2} age="1d" />
    </div>
  ),
};
